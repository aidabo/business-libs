/**
 * 面ナビ。この面の中の見出しへ飛ぶだけなので、面の一覧には依らない。
 *
 * 先頭を「第一面」と呼ばないのは、いま紙面の 1 面は政治面だから（faces.ts の
 * `print`）。同じ語を 2 つの意味で使うと、購読者にはどちらの第一面か分からない。
 * ここは新聞の面ではなく、この画面の一番上というだけなので「トップ」と呼ぶ。
 */
// 項目ごとの印（大きさ・色）は持たない。面ナビは全体を同じ大きさ・墨色で出し、
// 色を変えるのは現在地とホバーだけ（2026-10-07 第2弾のユーザー指示。第1弾で
// 放送の項目だけに付けた `emphasis` は、この指示で外した）。
export type NewsNavItem = {
  href: string;
  label: string;
};

export const NEWS_NAV: NewsNavItem[] = [
  { href: "#front", label: "トップ" },
  { href: "#flash", label: "速報" },
  // バーチャル放送（#broadcast）。紙面の帯は速報のすぐ下にあり、
  // 並びは紙面の DOM（NewsPaper）の順に揃える — useStickyNav は上から最初に
  // 見えている帯を現在地にするので、ここを入れ替えると現在地の印が実際の位置と
  // 食い違う（2026-10-07: 第一面の次から速報の次へ変更）。
  { href: "#broadcast", label: "バーチャル放送" },
  { href: "#faces", label: "ジャンル別" },
  { href: "#listen", label: "読み上げ" },
  { href: "#paper", label: "今日の電子紙面" },
  { href: "#ask", label: "AI に聞く" },
];

/** 面ナビの id（useStickyNav に渡す）。href の # を外したもの。 */
export const NEWS_NAV_IDS: string[] = NEWS_NAV.map((item) => item.href.replace(/^#/, ""));

/**
 * その面に出すナビ。読み上げ（#listen）とバーチャル放送（#broadcast）の
 * 帯は、出来ている記事がある日だけ出るので、無い日は項目も出さない
 * （押しても何も無い場所へ送らない）。
 * 帯そのものの出し分けは NewsPaper と BroadcastPage が持つ。
 */
export function navFor(
  hasListen: boolean,
  hasBroadcast = false,
): NewsNavItem[] {
  return NEWS_NAV.filter(
    (item) =>
      (hasListen || item.href !== "#listen") && (hasBroadcast || item.href !== "#broadcast"),
  );
}

/** navFor と同じ並びの id。現在地の監視（useStickyNav）に渡す。 */
export function navIdsFor(hasListen: boolean, hasBroadcast = false): string[] {
  return navFor(hasListen, hasBroadcast).map((item) => item.href.replace(/^#/, ""));
}

